export function tr(lang: string, key: string): string {
  return UI_TRANSLATIONS[lang]?.[key] || UI_TRANSLATIONS.en[key] || key;
}

export function isFullLanguage(lang: string): boolean {
  return FULL_LANG_CODES.has(lang);
}

export function pickLocalized<T>(record: Record<string, T> | undefined, lang: string): T | undefined {
  if (!record) return undefined;
  return record[lang] ?? record.en;
}
